"""Generate api/worker/src/withheldFloor.ts - the worker's fail-closed FLOOR of withheld series - from
api/worker/withheld.json (the committed copy of the list), or refresh that copy from the store first.

    python tools/gen_withheld_floor.py              # regenerate withheldFloor.ts from api/worker/withheld.json
    python tools/gen_withheld_floor.py --check      # exit 1 if withheldFloor.ts is not what withheld.json gives
    python tools/gen_withheld_floor.py --from-store # read _aqueduct/withheld.json from the store the worker
                                                    # reads (updater.blob.csv_store()), write withheld.json,
                                                    # then regenerate, so the committed floor follows the list
    python tools/gen_withheld_floor.py --from-store --check   # exit 1 if the committed copy is stale

The floor is used only when the live list cannot be read and the isolate holds no good copy (src/withheld.ts).
Its ids alone would NOT be fail-safe: an id withheld in the store after the floor was committed is not in it
(AR-341 finding 2). So while the floor applies, every source it names is withheld WHOLE, and
tools/withheld_list.py refuses to withhold an id of a source the committed floor does not name. A stale floor
therefore errs only CLOSED: it can re-hide a table un-hidden since (or a whole source), never show a withheld
one. tests/test_withheld_gate.py pins that the generated file matches the committed JSON (and that the check
can fail)."""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
JSON_PATH = os.path.join(ROOT, "api", "worker", "withheld.json")
TS_PATH = os.path.join(ROOT, "api", "worker", "src", "withheldFloor.ts")
KEY = "_aqueduct/withheld.json"
ID_RE = re.compile(r"^[a-z0-9_]+:[A-Za-z0-9_.-]+$")
MAX = 500


def validate(obj: dict) -> list[str]:
    """The worker's own rule (src/withheld.ts parseWithheld), in Python: refuse rather than emit a floor the
    worker would reject."""
    if not isinstance(obj, dict) or obj.get("version") != 1 or not isinstance(obj.get("ids"), dict):
        raise SystemExit("withheld.json: not {version: 1, ids: {...}}")
    ids = obj["ids"]
    if len(ids) > MAX:
        raise SystemExit(f"withheld.json: {len(ids)} ids > {MAX}")
    for k, v in ids.items():
        if not ID_RE.fullmatch(k):
            raise SystemExit(f"withheld.json: invalid id {k!r}")
        if not isinstance(v, dict) or v.get("until") not in ("complete", "operator"):
            raise SystemExit(f"withheld.json: {k}: 'until' must be 'complete' or 'operator'")
    return sorted(ids)


def render(ids: list[str]) -> str:
    tag = hashlib.sha256("\n".join(ids).encode("utf-8")).hexdigest()[:12]
    lines = ",\n".join(f'  "{i}"' for i in ids)
    return ("// GENERATED by tools/gen_withheld_floor.py from api/worker/withheld.json - do not edit by hand.\n"
            "// The fail-closed floor of src/withheld.ts: used ONLY when the live list cannot be read.\n"
            f"export const WITHHELD_FLOOR: readonly string[] = [\n{lines}{',' if ids else ''}\n];\n"
            f'export const WITHHELD_FLOOR_ETAG = "floor-{tag}";\n')


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--from-store", action="store_true")
    a = ap.parse_args(argv)
    if a.from_store:
        sys.path.insert(0, ROOT)
        from updater import blob                                              # noqa: PLC0415
        store = blob.csv_store()            # the store the worker reads (R2 before T0, the self-hosted one after)
        raw = store.get(KEY)
        if raw is None:
            raise SystemExit(f"{KEY} is absent from the store ({type(store).__name__}) - nothing to refresh from")
        live = json.loads(raw)
        validate(live)
        cur = json.load(open(JSON_PATH, encoding="utf-8"))
        if a.check:
            if sorted(cur["ids"]) != sorted(live["ids"]):
                print(f"STALE: api/worker/withheld.json lists {len(cur['ids'])} ids, the store {len(live['ids'])}; "
                      f"run without --check")
                return 1
            print("api/worker/withheld.json matches the store")
        else:
            with open(JSON_PATH, "w", encoding="utf-8", newline="\n") as fh:
                json.dump(live, fh, indent=1, sort_keys=True)
                fh.write("\n")
            print(f"api/worker/withheld.json refreshed from the store: {len(live['ids'])} ids")
    ids = validate(json.load(open(JSON_PATH, encoding="utf-8")))
    want = render(ids)
    have = open(TS_PATH, encoding="utf-8").read() if os.path.exists(TS_PATH) else ""
    if a.check and not a.from_store:
        if have.replace("\r\n", "\n") != want:
            print("STALE: src/withheldFloor.ts is not what withheld.json gives; run tools/gen_withheld_floor.py")
            return 1
        print(f"src/withheldFloor.ts matches withheld.json ({len(ids)} ids)")
        return 0
    if not a.check:
        with open(TS_PATH, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(want)
        print(f"src/withheldFloor.ts written: {len(ids)} ids")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
