"""Generate api/worker/src/freshnessClasses.ts - what the worker needs, beyond state rows, to print the public
freshness vocabulary ("late", "paused", "retired"; owner decisions 2026-10-20, core/freshness_vocab.py).

    python tools/gen_freshness_classes.py           # regenerate the file
    python tools/gen_freshness_classes.py --check   # exit 1 if the committed file is not what the code gives

Everything in the file is READ from the code, never typed: the registry (paused, rotating, served_by, and the
run mechanisms through tools/audit_schedule_coverage.scheduled_sources), updater/discontinued.yaml, the
health gate's SLA_TOLERANCE and deferral sentence, base.CADENCE_DAYS and NON_FAILURE_NOTES, and statcan's
LANE_CURRENT_PATTERN. So a registry edit that changes a class (a new paused key, a source taken off every
run) leaves the committed file stale, and tests/test_freshness_vocab.py fails until it is regenerated - the
worker cannot quietly keep the old answer. The classes are a function of public files only and are not
filtered by the redistribution gate (core.freshness_vocab.classes says why); the worker applies the gate to
its rows before it reads any class.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
TS_PATH = os.path.join(ROOT, "api", "worker", "src", "freshnessClasses.ts")


def _set(name: str, ids: list[str], doc: str) -> str:
    body = "".join(f"  {json.dumps(i)},\n" for i in ids)
    return f"// {doc}\nexport const {name}: ReadonlySet<string> = new Set<string>([\n{body}]);\n"


def render(c: dict) -> str:
    payload = json.dumps(c, sort_keys=True, ensure_ascii=True)
    tag = hashlib.sha256(payload.encode("utf-8")).hexdigest()[:12]
    cad = "".join(f"  {json.dumps(k)}: {v},\n" for k, v in sorted(c["cadence_days"].items()))
    paused = "".join(f"  {json.dumps(k)}: {json.dumps(v)},\n" for k, v in sorted(c["paused"].items()))
    nfn = "".join(f"  {json.dumps(p)},\n" for p in c["non_failure_notes"])
    tol = c["sla_tolerance"]
    return (
        "// GENERATED by tools/gen_freshness_classes.py - do not edit by hand (tests/test_freshness_vocab.py\n"
        "// fails when this file is not what the code gives). Read from updater/registry.yaml,\n"
        "// updater/discontinued.yaml, tools/audit_schedule_coverage.py, updater/health.py,\n"
        "// updater/strategies/base.py and updater/strategies/fetchers/statcan.py; the rule is\n"
        "// core/freshness_vocab.py, mirrored in src/freshness.ts.\n"
        f"export const FRESHNESS_CLASSES_TAG = \"fc-{tag}\";\n"
        "// updater.health.SLA_TOLERANCE: a source is late past this many cadence periods since its last success.\n"
        f"export const SLA_TOLERANCE = {int(tol) if float(tol).is_integer() else tol};\n"
        "// updater.strategies.base.CADENCE_DAYS - the health gate's clock (irregular = 7), NOT util.ts's\n"
        "// next_update_expected table.\n"
        f"export const LATE_CADENCE_DAYS: Readonly<Record<string, number>> = {{\n{cad}}};\n"
        "// registry `paused:` - source -> the reason the site shows.\n"
        f"export const PAUSED: Readonly<Record<string, string>> = {{\n{paused}}};\n"
        + _set("RUN_BY", c["run_by"], "Every source some run mechanism names (scheduled or stranded, lane, D1-only "
               "writers). Not in it, not paused, not discontinued = retired.")
        + _set("DISCONTINUED", c["discontinued"], "updater/discontinued.yaml (core/sync_state_d1.py also publishes "
               "these as status 'discontinued').")
        + _set("ROTATING", c["rotating"], "registry `rotating: true`: judged on its latest pass (a pure budget "
               "deferral is current).")
        + _set("LANE", c["lane"], "registry `served_by: lane`: judged on its reporter's latest verdict.")
        + "// statcan.LANE_CURRENT_PATTERN: the reporter verdicts that say the lane is current.\n"
        f"export const LANE_CURRENT_RE = new RegExp({json.dumps(c['lane_current'])});\n"
        "// updater.health._DEFERRAL_BASE: finalize()'s pure budget-deferral sentence, anchored.\n"
        f"export const DEFERRAL_RE = new RegExp({json.dumps(c['deferral'])});\n"
        "// updater.strategies.base.NON_FAILURE_NOTES: tails health._deferral_only drops before matching.\n"
        f"export const NON_FAILURE_NOTES: readonly string[] = [\n{nfn}];\n"
    )


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed file is stale")
    a = ap.parse_args(argv)
    from core import freshness_vocab
    want = render(freshness_vocab.classes())
    have = open(TS_PATH, encoding="utf-8").read() if os.path.exists(TS_PATH) else None
    if a.check:
        if have != want:
            print(f"STALE: {os.path.relpath(TS_PATH, ROOT)} is not what the code gives - run "
                  f"python tools/gen_freshness_classes.py and commit it", file=sys.stderr)
            return 1
        print(f"{os.path.relpath(TS_PATH, ROOT)} is current")
        return 0
    with open(TS_PATH, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(want)
    print(f"wrote {os.path.relpath(TS_PATH, ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
